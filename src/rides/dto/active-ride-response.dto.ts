import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

import { RideDirection, RideStatus, RideType } from '../enums/ride.enums';

export enum ActiveRideRole {
  DRIVER = 'DRIVER',
  PASSENGER = 'PASSENGER',
}

export class ActiveRideItemDto {
  @ApiProperty({ format: 'uuid' })
  rideId!: string;

  @ApiPropertyOptional({
    format: 'uuid',
    nullable: true,
    description: 'Passenger booking id. Present only for role=PASSENGER.',
  })
  bookingId?: string | null;

  @ApiProperty({ enum: ActiveRideRole, enumName: 'ActiveRideRole' })
  role!: ActiveRideRole;

  @ApiProperty({ enum: RideType, enumName: 'RideType' })
  rideType!: RideType;

  @ApiProperty({
    enum: [RideStatus.IN_PROGRESS],
    enumName: 'RideStatus',
  })
  status!: RideStatus.IN_PROGRESS;

  @ApiProperty({
    description:
      'Ride source, or the passenger booking pickup when stored (currently the ride source).',
  })
  source!: string;

  @ApiProperty({
    description:
      'Ride destination, or the passenger booking drop-off when stored (currently the ride destination).',
  })
  destination!: string;

  @ApiPropertyOptional({
    description:
      'PASSENGER only: this booking totalAmount in integer points (1 point = ₹1). Same as booking fareAmount.',
  })
  fare?: string;

  @ApiPropertyOptional({
    nullable: true,
    description:
      'PASSENGER only: existing 4-digit pickup OTP when WAITING_FOR_PICKUP. Null after pickup or when none is stored. Never generated by this endpoint.',
  })
  otp?: string | null;

  @ApiPropertyOptional({
    description:
      'DRIVER only: distinct CONFIRMED passengers on this IN_PROGRESS ride. PENDING, CANCELLED, rejected, and no-show bookings are excluded.',
  })
  totalPassengers?: number;

  @ApiPropertyOptional({
    description:
      'DRIVER only: sum of driver-facing fares on CONFIRMED bookings, in integer points. ' +
      'COMMUTE uses driverShareAmount when settled, otherwise driverPricePerSeatSnapshot × seats. ' +
      'REGULAR/ASSURED use booking totalAmount. This is not passenger-paid markup and not platform margin.',
  })
  totalFare?: string;

  @ApiPropertyOptional({
    format: 'uuid',
    nullable: true,
    description: 'Commute series id when this is a generated occurrence.',
  })
  seriesId?: string | null;

  @ApiPropertyOptional({
    nullable: true,
    example: '2026-10-29',
  })
  occurrenceDate?: string | null;

  @ApiPropertyOptional({
    enum: RideDirection,
    enumName: 'RideDirection',
    nullable: true,
  })
  direction?: RideDirection | null;
}

export class ActiveRidesResponseDto {
  @ApiProperty({ type: ActiveRideItemDto, isArray: true })
  items!: ActiveRideItemDto[];
}
